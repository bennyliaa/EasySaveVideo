    private val url = SourceUrl("https://media.example.invalid/selected.m3u8?signature=synthetic-secret")
    private val segment = SourceUrl("https://media.example.invalid/chunks/one.ts?signature=synthetic-secret")
    private val manifest = "#EXTM3U\n#EXT-X-ENDLIST\n".toByteArray()
    private fun resource(ref: RequestContextRef? = null) = SelectedMediaResource("candidate", "variant", url, requestContextRef = ref)
    private fun limits(max: Long = 64L * 1024 * 1024, total: Long = max * 3) =
        SaveLimits(max, total, noProgressTimeoutMillis = 2_000)
    private fun context(cancel: CancellationSource = CancellationSource(), bytes: Long? = null) =
        OperationContext("hls-operation", System.currentTimeMillis() + 30_000, cancel,
            retryBudget = 2, resourceBudget = ResourceBudget(maxBytes = bytes))
    private fun playlist(body: ByteArray = manifest, mime: String = "application/vnd.apple.mpegurl") =
        Response(body = ByteArrayInputStream(body), headers = headers(body.size.toLong(), mime))
    private fun ts(size: Long = 188, body: InputStream = GeneratedInput(size)) =
        Response(body = body, headers = headers(size, "video/mp2t"))
    private fun fetch(response: Response, sink: Sink = Sink(), maxBytes: Long = 64L * 1024 * 1024,
                      context: OperationContext = context(), limits: SaveLimits = limits(), progress: Progress = Progress()): HlsSegmentResponse =
        SystemHttpsHlsFetcher(connections = Factory(response)).fetchSegment(resource(), segment, sink, context, limits, maxBytes, progress)

    private fun privateResource(ref: RequestContextRef?, seed: PrivateNetworkSourceSeed = PrivateNetworkSourceSeed.create()) =
        resource(ref).copy(sourceIdentity = seed.sourceIdentity.encoded, privateSource = seed)

