    private fun headers(size: Long, mime: String) = mapOf("Content-Length" to "$size", "Content-Type" to mime)
    private fun hex(value: ByteArray) = value.joinToString("") { "%02x".format(it) }
    private fun fails(code: SaveError, action: () -> Any?): SaveFailure {
        try { action(); fail("Expected $code") } catch (failure: SaveFailure) { assertEquals(code, failure.code); return failure }
        throw AssertionError()
    }
    private class Progress : TransferProgress {
        var bytes = 0L; var restarts = 0; var failBytes = false
        val checkpoints = mutableListOf<DownloadCheckpoint>()
        override fun onBytes(delta: Long) { bytes += delta; if (failBytes) throw IllegalStateException("synthetic-secret") }
        override fun onRestart() { restarts++ }
        override fun onCheckpoint(checkpoint: DownloadCheckpoint) { checkpoints += checkpoint }
    }
    private class Sink : HlsSegmentSink {
        var size = 0L; var free = Long.MAX_VALUE; var opens = 0; var maxWrite = 0; var syncs = 0
        var closed = false; var failAt = ""; var afterWrite: ((Sink) -> Unit)? = null
        private fun check(step: String) { if (failAt == step) throw IOException("private-path-synthetic-secret") }
        override fun availableBytes() = free
        override fun length(): Long { check("length"); return size }
        override fun sync() { check("sync"); syncs++ }
        override fun open(): OutputStream {
            check("open"); opens++; size = 0
            return object : OutputStream() {
                override fun write(value: Int) { check("write"); size++; afterWrite?.invoke(this@Sink) }
                override fun write(value: ByteArray, offset: Int, count: Int) {
                    check("write"); size += count; maxWrite = maxOf(maxWrite, count); afterWrite?.invoke(this@Sink)
                }
                override fun close() { check("close"); closed = true }
            }
        }
    }
    private class GeneratedInput(private var remaining: Long) : InputStream() {
        var maxRead = 0; var closed = false; var failClose = false; var afterRead: (() -> Unit)? = null
        override fun read(): Int = if (remaining-- > 0) 7 else -1
        override fun read(value: ByteArray, offset: Int, count: Int): Int {
            maxRead = maxOf(maxRead, count)
            if (remaining <= 0) return -1
            val size = minOf(remaining, count.toLong()).toInt()
            java.util.Arrays.fill(value, offset, offset + size, 7.toByte())
            remaining -= size; afterRead?.invoke(); return size
        }
        override fun close() { if (failClose) throw IOException("synthetic-secret"); closed = true }
    }
    private class BlockingInput : InputStream() {
        val entered = CountDownLatch(1); val release = CountDownLatch(1); var closed = false
        override fun read(): Int { entered.countDown(); awaitUninterruptibly(release); throw IOException("synthetic-secret") }
        override fun read(value: ByteArray, offset: Int, count: Int) = read()
        override fun close() { closed = true }
    }
    private class Response(private val status: Int = 200, val body: InputStream = ByteArrayInputStream(byteArrayOf(1)), headers: Map<String, String> = emptyMap()) : HttpURLConnection(URL("https://script.example.invalid/")) {
        var disconnected = false; var inputRequests = 0; var statusRequests = 0
        var onDisconnect: (() -> Unit)? = null; var inputFailure: Exception? = null
        val requestHeaders = linkedMapOf<String, String>()
        val responseHeaders = headers.mapValues { listOf(it.value) }.toMutableMap()
        override fun connect() { }
        override fun disconnect() { disconnected = true; onDisconnect?.invoke() }
        override fun usingProxy() = false
        override fun getResponseCode(): Int { statusRequests++; return status }
        override fun getHeaderFields(): Map<String, List<String>> = responseHeaders
        override fun getInputStream(): InputStream { inputRequests++; inputFailure?.let { throw it }; return body }
        override fun setRequestProperty(key: String, value: String) { requestHeaders[key] = value }
    }
    private class Factory(vararg responses: Response) : DirectConnectionFactory {
        val requests = mutableListOf<URI>(); val timeouts = mutableListOf<Int>()
        private val responses = ArrayDeque(responses.toList())
        override fun open(uri: URI, connectTimeoutMillis: Int): HttpURLConnection { requests += uri; timeouts += connectTimeoutMillis; return responses.removeFirst() }
    }
    private class AsyncResult(val finished: CountDownLatch, val result: AtomicReference<Throwable?>) {
        fun awaitFailure(): SaveError {
            assertTrue("Controlled worker did not release", finished.await(3, TimeUnit.SECONDS))
            assertTrue("Expected sanitized failure", result.get() is SaveFailure)
            return (result.get() as SaveFailure).code
        }
    }
    private fun async(action: () -> Unit): AsyncResult {
        val finished = CountDownLatch(1); val result = AtomicReference<Throwable?>()
        Thread { try { action() } catch (failure: Throwable) { result.set(failure) } finally { finished.countDown() } }
            .apply { isDaemon = true; start() }
        return AsyncResult(finished, result)
    }
    companion object {
        private fun awaitUninterruptibly(latch: CountDownLatch) {
            var interrupted = false
            while (true) { try { latch.await(); break } catch (_: InterruptedException) { interrupted = true } }
            if (interrupted) Thread.currentThread().interrupt()
        }
    }
